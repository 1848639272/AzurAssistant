using System.IO;
using System.Media;

namespace AzurAssistant.Runtime;

/// <summary>
/// Short synthesized chimes for scheduled start/finish, plus playback of user-imported audio files. Waveforms are
/// generated in memory, so the assistant ships no audio asset, and every preset can be previewed at any volume.
/// </summary>
public static class TaskSound
{
    private const int SampleRate = 22050;

    // 100% waves, scaled per requested volume and cached so repeated previews stay cheap.
    private static readonly Dictionary<string, (byte[] Start, byte[] Finish)> Waves = Build();
    private static readonly Dictionary<(string Key, bool Start, int Volume), byte[]> Scaled = [];
    private static System.Windows.Media.MediaPlayer? _filePlayer;

    /// <summary>Directory holding user-imported audio; <c>file:</c> specs are resolved against it.</summary>
    public static string? SoundDirectory { get; set; }

    public static void PlayStart(string? spec, int volumePercent = 100) => PlaySpec(spec, start: true, volumePercent);
    public static void PlayFinish(string? spec, int volumePercent = 100) => PlaySpec(spec, start: false, volumePercent);

    private static void PlaySpec(string? spec, bool start, int volumePercent)
    {
        var volume = Math.Clamp(volumePercent, 0, 100);
        if (volume == 0) return;
        var normalized = ScheduleClock.NormalizeSound(spec);
        if (ScheduleClock.IsFileSpec(normalized))
        {
            PlayFile(normalized.Substring(ScheduleClock.FilePrefix.Length), volume);
            return;
        }
        Play(ScaledWave(normalized, start, volume));
    }

    private static byte[] ScaledWave(string key, bool start, int volume)
    {
        var cacheKey = (key, start, volume);
        lock (Scaled)
        {
            if (Scaled.TryGetValue(cacheKey, out var cached)) return cached;
            var scaled = Scale(start ? Waves[key].Start : Waves[key].Finish, volume);
            Scaled[cacheKey] = scaled;
            return scaled;
        }
    }

    /// <summary>Applies a linear gain to the PCM samples of a 16-bit mono wav generated by this class.</summary>
    private static byte[] Scale(byte[] wav, int volume)
    {
        if (volume >= 100) return wav;
        var gain = volume / 100.0;
        var copy = (byte[])wav.Clone();
        for (var offset = 44; offset + 1 < copy.Length; offset += 2)
        {
            var sample = BitConverter.ToInt16(copy, offset);
            BitConverter.GetBytes((short)(sample * gain)).CopyTo(copy, offset);
        }
        return copy;
    }

    /// <summary>Plays a user-imported wav/mp3/wma through the WPF media stack.</summary>
    private static void PlayFile(string name, int volume)
    {
        try
        {
            var path = Path.IsPathRooted(name) ? name : SoundDirectory is { } directory ? Path.Combine(directory, name) : name;
            if (!File.Exists(path)) return;
            _filePlayer?.Close();
            var player = new System.Windows.Media.MediaPlayer { Volume = Math.Clamp(volume, 0, 100) / 100.0 };
            player.MediaEnded += (_, _) => player.Close();
            player.MediaFailed += (_, _) => player.Close();
            player.Open(new Uri(path));
            player.Play();
            _filePlayer = player;
        }
        catch (Exception ex) when (ex is InvalidOperationException or UriFormatException or IOException or NotSupportedException) { }
    }

    private static void Play(byte[] wave)
    {
        // PlaySync blocks its own worker thread only; the UI thread stays responsive.
        _ = Task.Run(() =>
        {
            try
            {
                using var stream = new MemoryStream(wave, writable: false);
                using var player = new SoundPlayer(stream);
                player.PlaySync();
            }
            catch (Exception ex) when (ex is InvalidOperationException or IOException or PlatformNotSupportedException) { }
        });
    }

    private static Dictionary<string, (byte[] Start, byte[] Finish)> Build() => new(StringComparer.Ordinal)
    {
        ["chime"] = (Wave(0.35, (880, 90), (1320, 130)), Wave(0.35, (1320, 90), (880, 110), (660, 170))),
        ["soft"] = (Wave(0.35, (660, 150), (990, 190)), Wave(0.35, (990, 150), (740, 200), (550, 240))),
        ["deep"] = (Wave(0.35, (330, 170), (440, 210)), Wave(0.35, (440, 170), (330, 220), (220, 260))),
        ["double"] = (Wave(0.35, (880, 70), (0, 60), (880, 70), (0, 60)), Wave(0.35, (880, 70), (0, 60), (880, 70), (0, 60), (660, 150))),
    };

    private static byte[] Wave(double amplitude, params (double Hertz, int Milliseconds)[] notes)
    {
        var samples = new List<short>(notes.Sum(note => SampleRate * note.Milliseconds / 1000));
        foreach (var (hertz, milliseconds) in notes)
        {
            var count = SampleRate * milliseconds / 1000;
            for (var index = 0; index < count; index++)
            {
                if (hertz <= 0) { samples.Add(0); continue; }
                var progress = (double)index / count;
                // Smooth attack/release plus a gentle decay keeps the chime from clicking.
                var envelope = Math.Min(1, progress * 12) * Math.Min(1, (1 - progress) * 4) * (1 - progress * 0.35);
                var sample = Math.Sin(2 * Math.PI * hertz * index / SampleRate) * envelope * amplitude;
                samples.Add((short)(sample * short.MaxValue));
            }
        }
        using var output = new MemoryStream();
        using var writer = new BinaryWriter(output);
        var dataBytes = samples.Count * 2;
        writer.Write("RIFF"u8.ToArray());
        writer.Write(36 + dataBytes);
        writer.Write("WAVE"u8.ToArray());
        writer.Write("fmt "u8.ToArray());
        writer.Write(16);
        writer.Write((short)1);          // PCM
        writer.Write((short)1);          // mono
        writer.Write(SampleRate);
        writer.Write(SampleRate * 2);    // byte rate
        writer.Write((short)2);          // block align
        writer.Write((short)16);         // bits per sample
        writer.Write("data"u8.ToArray());
        writer.Write(dataBytes);
        foreach (var sample in samples) writer.Write(sample);
        writer.Flush();
        return output.ToArray();
    }
}
